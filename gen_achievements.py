TIERS = [("普通", 10), ("稀有", 25), ("史诗", 60), ("传说", 150)]


def A(cat, name, desc, points, tier, stat, val):
    return {"id": f"{stat}-{val}", "cat": cat, "name": name, "desc": desc,
            "points": points, "tier": tier, "stat": stat, "val": val}


def series(cat, names, desc_fmt, stat, vals, tiers=None):
    """names 与 vals 等长：每级一个成就。"""
    out = []
    for i, (n, v) in enumerate(zip(names, vals)):
        t, p = (tiers[i] if tiers else TIERS[min(i, 3)])
        out.append(A(cat, n, desc_fmt.format(v=v), p, t, stat, v))
    return out


